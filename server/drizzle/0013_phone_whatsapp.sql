-- Ticket numbers: a new ticket gets the lowest number that's free, so a
-- number left by a deleted ticket (even one in the middle) is used again.
-- The advisory lock makes two tickets made at the same moment take turns,
-- so they can't both get the same number.
CREATE OR REPLACE FUNCTION next_ticket_id() RETURNS integer
LANGUAGE plpgsql VOLATILE AS $$
DECLARE
  n integer;
BEGIN
  PERFORM pg_advisory_xact_lock(7342001);
  IF NOT EXISTS (SELECT 1 FROM tickets WHERE id = 1) THEN
    RETURN 1;
  END IF;
  SELECT t.id + 1 INTO n
    FROM tickets t
   WHERE NOT EXISTS (SELECT 1 FROM tickets x WHERE x.id = t.id + 1)
   ORDER BY t.id
   LIMIT 1;
  RETURN n;
END
$$;
